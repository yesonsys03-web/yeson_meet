r"""하우스 표기 강제 치환 — Task 18 (사람 번역본 전수 비교 P2).

캐릭터명·제작 용어의 하우스 표기가 사람 납품본(1090쌍 실측, 2026-07-30)과
불일치하거나 우리 출력 내부에서 혼재(Thatherton → 태더튼/새더튼)하는 문제를
KO→KO 결정적 치환으로 고정한다. 치환 방향은 전부 실측 검증됨(브리프 표 참고)
— 근거 없는 항목 추가 금지(강제 치환은 틀리면 맞는 번역을 틀리게 덮는다).

리뷰 후속(2026-07-30, 라운드 1): "이펙트 연기"/"연기 이펙트" 리터럴 2항목은
전수 1090쌍 재검증에서 실측 20건 중 6건만 잡는 것으로 드러났다(팀 리드 측정,
task-18-review.md Important 2) — 사람은 "이펙트"를 단 한 번도 쓰지 않고
항상 "<X> 효과"다. 리터럴 나열은 다음 에피소드(FX Water/FX Dust 등 미열거
항목)에서 깨지므로, 이 둘을 HOUSE_KO_PATTERN_CORRECTIONS(정규식 2개)로
교체했다.

리뷰 후속(2026-07-30, 라운드 2): 라운드 1의 `_SEG_END`가 비대칭이었다 —
세그먼트 시작은 ". " 뒤를 경계로 인정하는데 끝은 인정하지 않아, 리딩 규칙이
뒤따르는 문장 전체를 캡처로 삼켜 `효과`를 엉뚱한 문장 뒤로 밀어내는 결함이
있었다(task-18-rereview.md Important). `\.\s`를 `_SEG_END`에 추가해 대칭을
맞췄다. 같은 라운드에서 개행(`\n`/`\r`)도 경계로 접어넣었다 — Task 19가
액션 블록에 실제 줄바꿈을 도입하므로(슬러그라인 join), FX 라벨이 다음
줄에 오는 경우가 곧 실물이 된다.

리뷰 후속(2026-07-30, 라운드 3, 최종): 라운드 2의 수정은 `.`에만 대칭이고
이 태스크가 이미 dedupe 키(translate_blocks.py)에서 문말 부호로 정의해 둔
`? ! . …` 나머지 세 개에는 여전히 비대칭이었다(같은 결함 클래스,
task-18-rereview-round2.md Important A) — `[.?!…]\s`로 그 정의와 맞췄다.
같은 라운드에 또 하나: 캡처가 `.+?`라 `\r` 한 글자를 삼킬 수 있어(캡처는
최소 1글자 필요, `.`이 `\r`은 매치) CRLF가 떠돌이 `\r`+`\n`으로 쪼개지는
결함이 있었다(Important B) — 캡처를 `[^\r\n]+?`로 좁혀 개행 문자 자체가
캡처에 들어가는 일을 원천 차단했다(그 결과 `'이펙트 \r\n연기'` 같은 형태는
변환하지 않고 그대로 둔다 — 줄을 넘기거나 쪼개느니 미변환이 낫다는 방침).
"""
from __future__ import annotations

import re

# 사람 납품본 실측 기반 하우스 표기 (전수 비교 2026-07-30). KO→KO 결정적 치환.
# 표 12행(Thatherton은 새더튼·태더튼 2항목) 그대로 — 근거 없는 항목 추가 금지.
HOUSE_KO_CORRECTIONS: list[tuple[str, str]] = [
    ("조셉", "죠셉"), ("붐하워", "붐하우어"),
    ("새더튼", "대더튼"), ("태더튼", "대더튼"),
    ("레이 로이", "레이로이"), ("차 킹", "챠 킹"),
    # 제작 용어 — 과잉 치환 방지 위해 구체 패턴만:
    ("효과음:", "효과:"), ("프롭", "소품"), ("앵글 온:", "구도:"),
    ("설정 샷", "설정"), ("카메라 이동", "카메라 무브"),
    ("카메라 위치", "카메라 포즈"), ("새 아트", "뉴 아트"),
]

# 세그먼트 경계 — 문자열 시작/끝뿐 아니라, action 블록이 다른 지시문과
# " / "나 ". "로 이어붙는 실물 사례(전수 코퍼스 20건 중 2건 실측: "FX Fire"가
# 다른 액션노트와 " / "로 병합된 블록, "A long beat. FX Smoke"처럼 앞 문장
# 뒤에 곧장 붙는 블록)도 경계로 인정한다. 순수 ^/$ 앵커만 쓰면 이 2건을
# 놓친다(실측 확인, task-18-fix-report 참고).
#
# ⚠ _SEG_END는 _SEG_START와 대칭이어야 한다(라운드 2 리뷰가 잡은 결함):
# 시작 쪽은 문말 부호+공백 뒤를 경계로 인정하면서 끝 쪽은 "\s[./]"(공백+
# 구분자)만 인정하면, 실제 문장은 문말 부호가 단어에 바로 붙어 있으므로
# (예: "연기.") 문장 끝이 경계로 안 잡히고 리딩 규칙의 비탐욕 캡처가 다음
# 경계까지 뒤 문장 전체를 삼킨다 — 리딩 규칙은 캡처를 `효과` 앞으로
# 옮기므로, 삼켜진 문장째로 FX 라벨이 엉뚱한 문장 뒤에 붙는 틀린 주석이
# 된다(트레일링 규칙은 `\1`을 제자리에 되돌리므로 이 위험이 없다).
# 문말 부호 집합은 이 태스크가 dedupe 키(translate_blocks.py의
# `_DEDUPE_KEY_RE`)에서 이미 정의해 둔 `? ! . …` 그대로 맞춘다(한쪽만
# `.`으로 좁히면 같은 결함 클래스가 나머지 세 부호에 남는다 — 라운드 2→3에서
# 실제로 그랬다).
#
# 개행(`\r`/`\n`)도 양쪽 경계에 포함한다 — Task 19가 액션 블록에 실제
# 줄바꿈을 도입하므로(슬러그라인 join), FX 라벨이 다음 줄에 오는 경우가
# 실물이 된다. `.`은 기본적으로 `\n`을 매치하지 않는다(re.DOTALL 미사용,
# 의도적 — DOTALL을 쓰면 캡처가 줄 경계를 넘어 다른 줄의 텍스트까지
# 삼킬 수 있어 리딩 규칙 문제를 재현한다). 그 결과 `\n`/`\r` 뒤에서도
# 규칙이 발동한다(다음 줄의 FX 라벨도 잡힘).
#
# ⚠ 그것만으로는 캡처가 줄을 절대 넘지 않는다는 보장이 안 된다(라운드 2
# 주석의 착오 — 라운드 3 리뷰가 지적) — `.`은 `\r`은 매치하므로(제외되는
# 건 `\n`뿐), 캡처가 `[^\r\n]` 없이 `.+?`였다면 "이펙트 " 바로 뒤에 CR이
# 올 때 그 CR 한 글자가 캡처에 딸려가 `효과` 앞으로 옮겨지며 CRLF를
# 떠돌이 `\r`+`\n`으로 쪼갰다(내용 손실은 없지만 줄 구조 손상). 캡처
# 클래스를 `[^\r\n]+?`로 좁혀 개행 문자 자체가 캡처에 들어가는 일을
# 원천 차단한다 — 그 결과로 캡처가 줄을 넘어가는 일도, 개행 문자를
# 엉뚱한 자리로 옮기는 일도 없다(단, "이펙트 " 바로 뒤에 개행이 오면
# 캡처할 한 글자가 없어 규칙이 발동하지 않고 원문 그대로 남는다 — 줄을
# 쪼개거나 넘기느니 미변환을 택한 결과).
#
# 위 구분자(`/`·문말 부호+공백·개행) 이상으로 일반화하지 않는다(실측
# 근거 없는 델리미터 추가 금지).
_SEG_START = r"(?:^|(?<=[./]\s)|(?<=[\r\n]))"
_SEG_END = r"(?=\s[./]|[.?!…]\s|[\r\n]|$)"

# "FX <X>"/"<X> FX" → "<X> 효과" — 팀 리드 실측(전수 1090쌍, 2026-07-30
# 리뷰): 사람은 "이펙트"를 한 번도 쓰지 않고 전부 "<X> 효과"로 일관 — FX
# 뒤(앞)에 오는 대상 단어가 무엇이든 같은 규칙이 적용된다. 순서 고정(앞→뒤,
# 팀 리드 지시) — "이펙트"가 한 문자열에 두 번 나오는 이론적 edge case는
# 순서에 따라 결과가 달라지지만(테스트로 실측 고정 — 실물 코퍼스엔 이런
# 이중 출현이 없다), 정상 케이스(문자열당 1회)는 순서 무관하다. 사람이
# "카메라 플래시"를 "카메라 플래쉬"로 달리 쓰는 표기 차이(실측 n=1)는 이
# 규칙과 무관한 별개 이슈라 손대지 않는다.
HOUSE_KO_PATTERN_CORRECTIONS: list[tuple[re.Pattern[str], str]] = [
    (re.compile(_SEG_START + r"이펙트 ([^\r\n]+?)" + _SEG_END), r"\1 효과"),
    (re.compile(_SEG_START + r"([^\r\n]+?) 이펙트" + _SEG_END), r"\1 효과"),
]


def apply_house_style(ko: str) -> str:
    """HOUSE_KO_CORRECTIONS(리터럴)를 순서대로 적용한 뒤,
    HOUSE_KO_PATTERN_CORRECTIONS(정규식, FX 규칙)를 순서대로 적용한다.
    멱등 — 두 치환 모두 치환 결과 쪽에 자신의 좌변 문자열("이펙트" 포함)을
    재도입하지 않는다."""
    if not ko:
        return ko
    for wrong, right in HOUSE_KO_CORRECTIONS:
        if wrong in ko:
            ko = ko.replace(wrong, right)
    for pattern, replacement in HOUSE_KO_PATTERN_CORRECTIONS:
        ko = pattern.sub(replacement, ko)
    return ko

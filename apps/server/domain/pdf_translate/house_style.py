# ⚠왜 리터럴을 버리고 패턴으로 가는가: 이 자리는 리터럴 열거로 두 번 빗나갔다.
# 처음엔 `스프링 브레이커`(띄어씀)를 잡았더니 LLM이 `봄방학생`·`봄방학족`으로
# 샜고, 그 둘을 리터럴로 막았더니 이번엔 **띄어쓰기를 없앤** `스프링브레이커`와
# 새 접미사 `봄방학객`으로 샜다 — 재측정에서 앞선 리터럴 세 개가 잡은 건
# 0건이다. 흔들리는 축(띄어쓰기·접미사)을 패턴으로 흡수해야 같은 두더지가
# 다시 나오지 않는다.
#
# ⚠순서가 계약이다: `스프링브레이크`는 `스프링브레이커`의 **접두**라, 행사
# 규칙을 먼저 돌리면 `봄방학어`가 된다. 역할 규칙이 반드시 앞에 온다
# (테스트로 잠금).
#
# ⚠공백은 `[ \t]*`다(`\s*` 아님) — `\s`는 개행을 삼켜서 줄이 갈린 자리의
# 두 낱말을 한 줄로 합쳐 버린다(_SCENE_REF_RE가 같은 이유로 같은 선택을 했다).
#
# ⚠접미사는 **관측된 것만** 연다(생·족·객). `봄방학` 단독(행사)은 접미사를
# 요구하는 이 패턴에 걸리지 않으므로 그대로 남는다 — 사람도 9건 쓰는 정상
# 번역이다(테스트로 잠금).
#
# 성별 접두도 같은 자리의 잔여다 — `여성`·`남성`은 사람 납품본에 **0건**이고
# 우리 출력에서도 이 역할명 블록(p28·p42)에서만 8건 나온다(그 밖에서는
# 이미 `여자` 24 / `남자` 13으로 사람 25/14와 맞는다). `파티광` 토큰을
# 요구하므로 평범한 대사의 `여성`은 덮지 않는다. 역할명 치환이 먼저 돌아
# `파티광`을 만들어 둔 뒤라야 걸리므로 순서상 마지막이다.
HOUSE_KO_SPRING_BREAK_CORRECTIONS: list[tuple[re.Pattern[str], str]] = [
    (re.compile(r"스프링[ \t]*브레이커"), "파티광"),
    (re.compile(r"봄방학[ \t]*(?:생|족|객)"), "파티광"),
    (re.compile(r"스프링[ \t]*브레이크"), "봄방학"),
    (re.compile(r"여성[ \t]*파티광"), "여자파티광"),
    (re.compile(r"남성[ \t]*파티광"), "남자파티광"),
]

# 씬 번호 표기(Task 20, 사용자 지적 2026-07-31) — 애니메이션 스토리보드에서
# `sc` 뒤에 숫자가 붙은 토큰은 **씬 번호**다. 전수 실측(pairs_all.jsonl
# 1095쌍): 원문에 `sc+숫자`가 있는 블록 14건 중 사람은 14/14 전부 `씬`으로
# 옮겼다(예외 0건) — LLM 문맥 추론에 맡기면 9/14만 맞았으므로(나머지 5건은
# `sc`를 그대로 뒀다) 결정적 치환으로 고정한다.
#
# 숫자는 캡처 그룹을 그대로 옮긴다 — 이 규칙 자체는 숫자를 절대 만들거나
# 바꾸지 않는다(테스트로 잠금). 사용자 요구가 "특히 숫자는 틀리면 안 된다"라
# 숫자 불변은 이 규칙의 계약이다.
#
# ⚠ 왼쪽 가드 필수 — 없으면 `discuss`·`disc03`처럼 단어 안의 `sc`에
# 오폭한다. 오른쪽은 뒤따르는 `\d+` 요구가 `scene`·`score`(숫자가 안 옴)를
# 막는다. 두 가드가 함께 있어야 한다.
#
# ⚠ 왼쪽 가드는 `\b`가 아니라 `(?<![0-9A-Za-z_])`다(리뷰 지적, 2026-07-31).
# 파이썬 `\b`는 **한글을 단어 문자로 취급**하므로 `"이전sc49"`처럼 한글이
# 공백 없이 바로 앞에 오면 경계가 성립하지 않아 매치를 놓친다.
# 라틴 문자·숫자만 배제하면 한글 인접은 잡히면서 `discuss`(앞이 `i`)·
# `disc03`(앞이 `i`)·`HANKSC12`(앞이 `K`)는 그대로 막힌다.
#
# 근거의 정확한 범위(2026-07-31 코퍼스 재실측, pairs_all.jsonl 1090쌍):
# 사람 납품본 `human_ko`에 **한글 바로 뒤 `sc`+숫자는 0건**이다 — 사람은
# `sc`를 남기지 않고 항상 `씬`으로 옮기기 때문이다. 즉 "사람이 `이전sc49`를
# 쓴다"는 근거는 없다(앞선 판의 주석은 그렇게 읽혔다 — 정정). 실측된 것은
# **씬 토큰이 앞 한글에 공백 없이 붙는 표기**다(`전씬49` 2건). 이 규칙의
# 입력은 사람 번역이 아니라 **LLM 출력**이고, LLM이 씬 토큰을 앞 한글에
# 붙여 쓰면서 `sc`만 못 옮긴 형태(`이전sc49`)는 그 표기 습관상 충분히
# 나올 수 있는 모양이다 — 관측된 누락이 아니라 가능한 누락을 막는 것이다.
#
# `_`를 배제 집합에 넣어 둔 건 `\b` 시절 동작을 유지하려는 것이다 —
# 파이썬 정규식에서 `_`는 단어 문자라 `\b`가 `_sc12`를 막고 있었고,
# 자산 코드(`BG_sc12`류)가 씬 참조로 오인되지 않게 그 성질을 보존한다.
#
# ⚠ 공백은 `\s`가 아니라 `[ \t]`다 — `\s`는 개행도 삼켜서 "…sc\n49…"처럼
# 줄이 갈린 곳에서 **다음 줄의 숫자**를 씬 번호로 끌어온다. Task 19가 액션
# 블록에 실제 줄바꿈을 도입했으므로(슬러그라인 join) 이건 이론이 아니라
# 실물에서 가능한 형태다. 줄을 넘는 결합은 하지 않는다.
_SCENE_REF_RE = re.compile(r"(?<![0-9A-Za-z_])sc[ \t]*(\d+)", re.IGNORECASE)


def apply_house_style(ko: str) -> str:
    """HOUSE_KO_CORRECTIONS(리터럴) → HOUSE_KO_PATTERN_CORRECTIONS(정규식,
    FX 규칙) → SPRING BREAK 계열 → 씬 번호 표기(_SCENE_REF_RE) 순으로 적용한다.

    멱등 — 네 치환 모두 결과 쪽에 자신의 좌변("이펙트", `스프링…`, `sc<숫자>`)을
    재도입하지 않는다(SPRING BREAK 규칙의 결과 `파티광`·`봄방학`은 그 자체로는
    어느 좌변에도 맞지 않는다 — `봄방학`은 접미사를 요구하는 좌변에 걸리지
    않는다). 씬 규칙을 마지막에 두는 건 앞 규칙들의 치환 결과에 새
    `sc<숫자>`가 생길 수 없기 때문이라 순서 의존은 아니지만, 회귀 감지를
    위해 테스트로 고정한다."""
    if not ko:
        return ko
    for wrong, right in HOUSE_KO_CORRECTIONS:
        if wrong in ko:
            ko = ko.replace(wrong, right)
    for pattern, replacement in HOUSE_KO_PATTERN_CORRECTIONS:
        ko = pattern.sub(replacement, ko)
    for pattern, replacement in HOUSE_KO_SPRING_BREAK_CORRECTIONS:
        ko = pattern.sub(replacement, ko)
    return _SCENE_REF_RE.sub(r"씬 \1", ko)

from __future__ import annotations

import re

# 사람 납품본 실측 기반 하우스 표기 (전수 비교 2026-07-30). KO→KO 결정적 치환.
# 표 12행(Thatherton은 새더튼·태더튼 2항목) 그대로 — 근거 없는 항목 추가 금지.
HOUSE_KO_CORRECTIONS: list[tuple[str, str]] = [
    ("조셉", "죠셉"), ("붐하워", "붐하우어"),
    ("새더튼", "대더튼"), ("태더튼", "대더튼"),
    ("레이 로이", "레이로이"), ("차 킹", "챠 킹"),
    # 제작 용어 — 과잉 치환 방지 위해 구체 패턴만:
    ("효과음:", "효과:"), ("프롭", "소품"), ("앵글 온:", "구도:"),
    ("설정 샷", "설정"), ("카메라 이동", "카메라 무브"),
    ("카메라 위치", "카메라 포즈"), ("새 아트", "뉴 아트"),
]

# 세그먼트 경계 — 문자열 시작/끝뿐 아니라, action 블록이 다른 지시문과
# " / "나 ". "로 이어붙는 실물 사례(전수 코퍼스 20건 중 2건 실측: "FX Fire"가
# 다른 액션노트와 " / "로 병합된 블록, "A long beat. FX Smoke"처럼 앞 문장
# 뒤에 곧장 붙는 블록)도 경계로 인정한다. 순수 ^/$ 앵커만 쓰면 이 2건을
# 놓친다(실측 확인, task-18-fix-report 참고).
#
# ⚠ _SEG_END는 _SEG_START와 대칭이어야 한다(라운드 2 리뷰가 잡은 결함):
# 라운드 1의 끝 쪽은 "\s[./]"(공백+구분자)만 인정했는데, 실제 문장은
# 문말 부호가 단어에 바로 붙어 있으므로(예: "연기.") 문장 끝이 경계로 안
# 잡히고 리딩 규칙의 비탐욕 캡처가 다음 경계까지 뒤 문장 전체를 삼켰다 —
# 리딩 규칙은 캡처를 `효과` 앞으로 옮기므로, 삼켜진 문장째로 FX 라벨이
# 엉뚱한 문장 뒤에 붙는 틀린 주석이 된다(트레일링 규칙은 `\1`을 제자리에
# 되돌리므로 이 위험이 없다). 문말 부호 집합은 이 태스크가 dedupe 키
# (translate_blocks.py의 `_DEDUPE_KEY_RE`)에서 이미 정의해 둔 `? ! . …`
# 그대로 맞춘다(한쪽만 `.`으로 좁히면 같은 결함 클래스가 나머지 세 부호에
# 남는다 — 라운드 2→3에서 실제로 그랬다).
#
# ⚠ 비대칭은 고쳐진 게 아니라 방향이 바뀌었을 뿐이다(2026-07-30 정정):
# 시작 쪽(`_SEG_START`)은 `.`·`/`+공백만 인정하고, 끝 쪽(`_SEG_END`)은
# 문말 부호 전체(`.?!…`)+공백을 인정한다 — START의 `?!…`는 실측 근거가
# 없어 넓히지 않았다. 결과는 놓친 변환뿐(START 쪽 경계로 못 잡는 세그먼트는
# 그냥 미변환으로 남는다)이지 손상이 아니다.
#
# 개행(`\r`/`\n`)도 양쪽 경계에 포함한다 — Task 19가 액션 블록에 실제
# 줄바꿈을 도입하므로(슬러그라인 join), FX 라벨이 다음 줄에 오는 경우가
# 실물이 된다. `.`은 기본적으로 `\n`을 매치하지 않는다(re.DOTALL 미사용,
# 의도적 — DOTALL을 쓰면 캡처가 줄 경계를 넘어 다른 줄의 텍스트까지
# 삼킬 수 있어 리딩 규칙 문제를 재현한다). 그 결과 `\n`/`\r` 뒤에서도
# 규칙이 발동한다(다음 줄의 FX 라벨도 잡힘).
#
# ⚠ 그것만으로는 캡처가 줄을 절대 넘지 않는다는 보장이 안 된다(라운드 2
# 주석의 착오 — 라운드 3 리뷰가 지적) — `.`은 `\r`은 매치하므로(제외되는
# 건 `\n`뿐), 캡처가 `[^\r\n]` 없이 `.+?`였다면 "이펙트 " 바로 뒤에 CR이
# 올 때 그 CR 한 글자가 캡처에 딸려가 `효과` 앞으로 옮겨지며 CRLF를
# 떠돌이 `\r`+`\n`으로 쪼갰다(내용 손실은 없지만 줄 구조 손상). 캡처
# 클래스를 `[^\r\n]+?`로 좁혀 개행 문자 자체가 캡처에 들어가는 일을
# 원천 차단한다 — 그 결과로 캡처가 줄을 넘어가는 일도, 개행 문자를
# 엉뚱한 자리로 옮기는 일도 없다(단, "이펙트 " 바로 뒤에 개행이 오면
# 캡처할 한 글자가 없어 규칙이 발동하지 않고 원문 그대로 남는다 — 줄을
# 쪼개거나 넘기느니 미변환을 택한 결과).
#
# 위 구분자(`/`·문말 부호+공백·개행) 이상으로 일반화하지 않는다(실측
# 근거 없는 델리미터 추가 금지).
_SEG_START = r"(?:^|(?<=[./]\s)|(?<=[\r\n]))"
_SEG_END = r"(?=\s[./]|[.?!…]\s|[\r\n]|$)"

# "FX <X>"/"<X> FX" → "<X> 효과" — 팀 리드 실측(전수 1090쌍, 2026-07-30
# 리뷰): 사람은 "이펙트"를 한 번도 쓰지 않고 전부 "<X> 효과"로 일관 — FX
# 뒤(앞)에 오는 대상 단어가 무엇이든 같은 규칙이 적용된다. 순서 고정(앞→뒤,
# 팀 리드 지시) — "이펙트"가 한 문자열에 두 번 나오는 이론적 edge case는
# 순서에 따라 결과가 달라지지만(테스트로 실측 고정 — 실물 코퍼스엔 이런
# 이중 출현이 없다), 정상 케이스(문자열당 1회)는 순서 무관하다. 사람이
# "카메라 플래시"를 "카메라 플래쉬"로 달리 쓰는 표기 차이(실측 n=1)는 이
# 규칙과 무관한 별개 이슈라 손대지 않는다.
HOUSE_KO_PATTERN_CORRECTIONS: list[tuple[re.Pattern[str], str]] = [
    (re.compile(_SEG_START + r"이펙트 ([^\r\n]+?)" + _SEG_END), r"\1 효과"),
    (re.compile(_SEG_START + r"([^\r\n]+?) 이펙트" + _SEG_END), r"\1 효과"),
]

# 씬 번호 표기(Task 20, 사용자 지적 2026-07-31) — 애니메이션 스토리보드에서
# `sc` 뒤에 숫자가 붙은 토큰은 **씬 번호**다. 전수 실측(pairs_all.jsonl
# 1095쌍): 원문에 `sc+숫자`가 있는 블록 14건 중 사람은 14/14 전부 `씬`으로
# 옮겼다(예외 0건) — LLM 문맥 추론에 맡기면 9/14만 맞았으므로(나머지 5건은
# `sc`를 그대로 뒀다) 결정적 치환으로 고정한다.
#
# 숫자는 캡처 그룹을 그대로 옮긴다 — 이 규칙 자체는 숫자를 절대 만들거나
# 바꾸지 않는다(테스트로 잠금). 사용자 요구가 "특히 숫자는 틀리면 안 된다"라
# 숫자 불변은 이 규칙의 계약이다.
#
# ⚠ 왼쪽 가드 필수 — 없으면 `discuss`·`disc03`처럼 단어 안의 `sc`에
# 오폭한다. 오른쪽은 뒤따르는 `\d+` 요구가 `scene`·`score`(숫자가 안 옴)를
# 막는다. 두 가드가 함께 있어야 한다.
#
# ⚠ 왼쪽 가드는 `\b`가 아니라 `(?<![0-9A-Za-z_])`다(리뷰 지적, 2026-07-31).
# 파이썬 `\b`는 **한글을 단어 문자로 취급**하므로 `"이전sc49"`처럼 한글이
# 공백 없이 바로 앞에 오면 경계가 성립하지 않아 매치를 놓친다 — 사람
# 납품본이 `이전씬49`를 붙여 쓰는 실물 형태라 이건 실제 누락이었다.
# 라틴 문자·숫자만 배제하면 한글 인접은 잡히면서 `discuss`(앞이 `i`)·
# `disc03`(앞이 `i`)·`HANKSC12`(앞이 `K`)는 그대로 막힌다.
#
# `_`를 배제 집합에 넣어 둔 건 `\b` 시절 동작을 유지하려는 것이다 —
# 파이썬 정규식에서 `_`는 단어 문자라 `\b`가 `_sc12`를 막고 있었고,
# 자산 코드(`BG_sc12`류)가 씬 참조로 오인되지 않게 그 성질을 보존한다.
#
# ⚠ 공백은 `\s`가 아니라 `[ \t]`다 — `\s`는 개행도 삼켜서 "…sc\n49…"처럼
# 줄이 갈린 곳에서 **다음 줄의 숫자**를 씬 번호로 끌어온다. Task 19가 액션
# 블록에 실제 줄바꿈을 도입했으므로(슬러그라인 join) 이건 이론이 아니라
# 실물에서 가능한 형태다. 줄을 넘는 결합은 하지 않는다.
_SCENE_REF_RE = re.compile(r"(?<![0-9A-Za-z_])sc[ \t]*(\d+)", re.IGNORECASE)


def apply_house_style(ko: str) -> str:
    """HOUSE_KO_CORRECTIONS(리터럴) → HOUSE_KO_PATTERN_CORRECTIONS(정규식,
    FX 규칙) → 씬 번호 표기(_SCENE_REF_RE) 순으로 적용한다.

    멱등 — 세 치환 모두 결과 쪽에 자신의 좌변("이펙트", `sc<숫자>`)을
    재도입하지 않는다. 씬 규칙을 마지막에 두는 건 앞 규칙들의 치환 결과에
    새 `sc<숫자>`가 생길 수 없기 때문이라 순서 의존은 아니지만, 회귀
    감지를 위해 테스트로 고정한다."""
    if not ko:
        return ko
    for wrong, right in HOUSE_KO_CORRECTIONS:
        if wrong in ko:
            ko = ko.replace(wrong, right)
    for pattern, replacement in HOUSE_KO_PATTERN_CORRECTIONS:
        ko = pattern.sub(replacement, ko)
    return _SCENE_REF_RE.sub(r"씬 \1", ko)
